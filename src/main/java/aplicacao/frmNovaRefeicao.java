    private void btnPreparoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPreparoActionPerformed
        try {
            // 1. Converte o texto dos campos para inteiro
            int tempoMaximo = Integer.parseInt(tempofield.getText().trim());
            String caloriaTexto = caloriafield.getText().trim();
            int caloriaMax = caloriaTexto.isEmpty() ? 0 : Integer.parseInt(caloriaTexto);
            int componentes = Integer.parseInt(componentefield.getText().trim());

            // 2. Validação para impedir valores <= 0
            if (tempoMaximo <= 0 || componentes <= 0) {
                JOptionPane.showMessageDialog(this,
                        "Tempo, número de pratos e calorias devem ser valores positivos.",
                        "Aviso",
                        JOptionPane.WARNING_MESSAGE);
                return; // STOP: Interrompe a execução para não criar a refeição inválida
            }

            // 3. Cria e prepara a refeição
            System.out.println("Caloria " + caloriaMax);

            Refeicao novaRefeicao = new Refeicao(tempoMaximo, componentes, caloriaMax);
            List<Prato> menu = daoPrato.listar();
            List<Ingrediente> dispensa = daoIng.listar();
            novaRefeicao.prepararRefeicao(menu, dispensa);
            if (refeicao != null) {
                novaRefeicao.setId(refeicao.getId());
            }
            this.refeicao = novaRefeicao;
            JOptionPane.showMessageDialog(this, "Refeição gerada com sucesso!");
            preencherTabelas();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Por favor, preencha todos os campos apenas com números inteiros válidos.",
                    "Erro de Digitação",
                    JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Erro ao preparar refeição: " + e.getMessage());
        }

    }//GEN-LAST:event_btnPreparoActionPerformed

