    private void btnAceitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceitarActionPerformed
        if (this.verifica) {

            int verific = daoRef.editar(refeicao);
            if (verific > 0) {

                new frmPrincipal().setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao editar refeição");
            }
        } else {
            int verific = daoRef.inserir(refeicao);
            if (verific > 0) {

                new frmPrincipal().setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao inserir refeição");
            }
        }
    }//GEN-LAST:event_btnAceitarActionPerformed

